class TestDataProvenance:
    def test_trade_flows_csv_exists(self):
        """trade_flows.csv must exist (generated by ETL pipeline)."""
        assert TRADE_FLOWS_CSV.exists(), (
            f"trade_flows.csv not found at {TRADE_FLOWS_CSV}. "
            f"Run: python apps/api/ml/scripts/download/ingest_real_trade.py"
        )

    def test_trade_flows_csv_has_records(self):
        """trade_flows.csv must have at least 500 bilateral flow records."""
        with open(TRADE_FLOWS_CSV, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
        assert len(rows) >= 500, f"Expected ≥500 rows, got {len(rows)}"

    def test_trade_flows_covers_major_economies(self):
        """Must cover top 10 economies (USA, CHN, DEU, JPN, IND, GBR, FRA, BRA, CAN, KOR)."""
        required = {"USA", "CHN", "DEU", "JPN", "IND", "GBR", "FRA", "BRA", "CAN", "KOR"}
        with open(TRADE_FLOWS_CSV, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            covered = set()
            for row in reader:
                covered.add(row["source_iso3"])
                covered.add(row["target_iso3"])
        missing = required - covered
        assert not missing, f"Missing major economies in trade_flows.csv: {missing}"

    def test_trade_flows_no_zero_values(self):
        """All export values must be > 0 (no fabricated zero-volume flows)."""
        with open(TRADE_FLOWS_CSV, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            zero_count = 0
            for row in reader:
                exp = float(row.get("export_value_usd") or 0)
                imp = float(row.get("import_value_usd") or 0)
                if exp <= 0 and imp <= 0:
                    zero_count += 1
        assert zero_count == 0, f"Found {zero_count} rows with zero export AND import value"

    def test_usa_chn_corridor_exists(self):
        """USA-CHN is the world's largest bilateral trade corridor — must be present."""
        with open(TRADE_FLOWS_CSV, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            found = any(
                row["source_iso3"] == "USA" and row["target_iso3"] == "CHN"
                for row in reader
            )
        assert found, "USA→CHN bilateral corridor missing from trade_flows.csv"

    def test_usa_chn_value_in_billions(self):
        """USA→CHN export value must be in the hundreds of billions USD range (real data validation)."""
        with open(TRADE_FLOWS_CSV, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if row["source_iso3"] == "USA" and row["target_iso3"] == "CHN" and row["year"] == "2022":
                    exp = float(row["export_value_usd"])
                    # Real 2022 USA→CHN exports: ~$153.8B
                    assert exp > 1e10, f"USA→CHN 2022 export too low: ${exp:.0f} (expected >$10B)"
                    assert exp < 2e12, f"USA→CHN 2022 export implausibly high: ${exp:.0f}"
                    return
        pytest.skip("USA→CHN 2022 row not found — ETL may use different year range")

    def test_no_random_import_in_seed_script(self):
        """seed_neo4j_trade.py must NOT import the random module."""
        seed_path = PROJECT_ROOT / "apps" / "api" / "scripts" / "seed_neo4j_trade.py"
        content = seed_path.read_text(encoding="utf-8")
        assert "import random" not in content, (
            "seed_neo4j_trade.py still imports the random module — fabricated data not removed"
        )
        assert "random.uniform" not in content, (
            "seed_neo4j_trade.py still uses random.uniform — fabricated data not removed"
        )

    def test_offline_cache_exists(self):
        """cached_network.json must exist for offline fallback."""
        assert CACHED_NETWORK_JSON.exists(), (
            f"cached_network.json not found at {CACHED_NETWORK_JSON}. "
            f"Run the ETL pipeline to regenerate."
        )

    def test_offline_cache_structure(self):
        """cached_network.json must have nodes and edges with real ISO3 IDs."""
        with open(CACHED_NETWORK_JSON, encoding="utf-8") as f:
            data = json.load(f)
        assert "nodes" in data, "cached_network.json missing 'nodes' key"
        assert "edges" in data, "cached_network.json missing 'edges' key"
        assert len(data["nodes"]) >= 30, f"Expected ≥30 nodes, got {len(data['nodes'])}"
        assert len(data["edges"]) >= 50, f"Expected ≥50 edges, got {len(data['edges'])}"

        # All node IDs must be ISO3 codes (3 uppercase letters)
        for node in data["nodes"]:
            assert len(node["id"]) == 3, f"Non-ISO3 node ID: {node['id']!r}"
            assert node["id"].isupper(), f"Node ID not uppercase ISO3: {node['id']!r}"

    def test_offline_cache_usa_chn_present(self):
        """USA and CHN must be in the offline network cache."""
        with open(CACHED_NETWORK_JSON, encoding="utf-8") as f:
            data = json.load(f)
        node_ids = {n["id"] for n in data["nodes"]}
        assert "USA" in node_ids, "USA missing from cached_network.json nodes"
        assert "CHN" in node_ids, "CHN missing from cached_network.json nodes"

