"""
Phase 22 — Resilient GraphRepository with ISO3 Standardization
================================================================
Key changes vs. pre-Phase 22 implementation:

  TN-02 Fixed: Neo4j ServiceUnavailable is caught; falls back to
               cached_network.json offline snapshot (never HTTP 500)

  TN-03 Fixed: Node IDs use iso3 property (e.g. "USA") instead of
               internal element IDs (e.g. "4:624f21a6-...").
               Source/target edges use iso3 start/end node properties.

  TN-06 Support: get_network(year) accepts an optional year filter,
                 enabling the timeline slider to retrieve year-specific data.

  TN-09 Mitigation: No randomize in Cypher; consistent order via iso3.
"""
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

from app.neo4j.session import neo4j_conn
from app.schemas.graph import GraphResponse, GraphNode, GraphEdge

log = logging.getLogger(__name__)

# Offline fallback cache generated by the Phase 22 ETL pipeline
_CACHE_PATH = Path(__file__).resolve().parents[4] / "data" / "processed" / "cached_network.json"

# In-memory cache of fallback data (loaded once on first failure)
_fallback_cache: Optional[GraphResponse] = None


def _load_fallback_cache() -> GraphResponse:
    """
    Load the offline cached network snapshot.
    Returns GraphResponse from cached_network.json.
    Caches result in memory after first load.
    """
    global _fallback_cache
    if _fallback_cache is not None:
        return _fallback_cache

    if not _cache_path_exists():
        log.warning("Offline cache file not found at %s — returning empty graph", _CACHE_PATH)
        return GraphResponse(nodes=[], edges=[])

    try:
        with open(_CACHE_PATH, encoding="utf-8") as f:
            data = json.load(f)

        nodes = [
            GraphNode(
                id=n["id"],
                label=n.get("label", "Country"),
                properties=n.get("properties", {})
            )
            for n in data.get("nodes", [])
        ]
        edges = [
            GraphEdge(
                id=e["id"],
                source=e["source"],
                target=e["target"],
                type=e.get("type", "EXPORTS_TO"),
                properties=e.get("properties", {})
            )
            for e in data.get("edges", [])
        ]
        _fallback_cache = GraphResponse(nodes=nodes, edges=edges)
        log.info(
            "Loaded offline trade network cache: %d nodes, %d edges",
            len(nodes), len(edges)
        )
        return _fallback_cache

    except (json.JSONDecodeError, KeyError, TypeError) as e:
        log.error("Failed to load offline cache: %s", e)
        return GraphResponse(nodes=[], edges=[])


def _cache_path_exists() -> bool:
    return _CACHE_PATH.exists()


def _filter_cache_by_year(response: GraphResponse, year: Optional[int]) -> GraphResponse:
    """
    Filter the cached network edges by a specific year.
    If year is None, returns all edges (multi-year aggregate snapshot).
    """
    if year is None:
        return response
    filtered_edges = [
        e for e in response.edges
        if e.properties.get("year") == year
    ]
    if not filtered_edges:
        # Year not in cache — return all edges (best-effort graceful degradation)
        return response
    return GraphResponse(nodes=response.nodes, edges=filtered_edges)


class GraphRepository:
    """
    Repository for Neo4j trade knowledge graph with offline PostgreSQL fallback.

    Node IDs are standardized to sovereign ISO3 codes (e.g. "USA") throughout.
    """

    async def run_query(
        self,
        query: str,
        parameters: Dict[str, Any] = None
    ) -> GraphResponse:
        """
        Execute a Cypher read query against Neo4j.
        On ServiceUnavailable or driver failure, returns empty response
        (caller should invoke fallback).

        ISO3 standardization:
          - Nodes: id = node.iso3 (falls back to element_id if missing)
          - Edges: source/target = start/end node iso3 (falls back to element_id)
        """
        parameters = parameters or {}
        nodes_dict: Dict[str, GraphNode] = {}
        edges_list: list[GraphEdge] = []

        def _node_id(value) -> str:
            """Extract ISO3 from node properties, or fall back to element_id."""
            props = dict(value.items())
            iso3 = props.get("iso3") or props.get("id")
            if iso3:
                return str(iso3)
            return str(value.element_id)

        def _register_node(value) -> str:
            node_id = _node_id(value)
            if node_id not in nodes_dict:
                nodes_dict[node_id] = GraphNode(
                    id=node_id,
                    label=list(value.labels)[0] if value.labels else "Node",
                    properties=dict(value.items())
                )
            return node_id

        async def fetch_data(tx):
            result = await tx.run(query, parameters)
            return [record async for record in result]

        try:
            async with neo4j_conn.driver.session() as session:
                records = await session.execute_read(fetch_data)
        except Exception as e:
            log.warning("Neo4j query failed (%s): %s", type(e).__name__, e)
            raise  # Bubble up so callers can trigger fallback

        for record in records:
            for key, value in record.items():
                if hasattr(value, "labels"):  # Node
                    _register_node(value)

                elif hasattr(value, "type") and hasattr(value, "start_node"):  # Relationship
                    edge_id = str(value.element_id)
                    # Use ISO3 for edge endpoints
                    src_id = _node_id(value.start_node) if hasattr(value.start_node, "items") else str(value.start_node.element_id)
                    tgt_id = _node_id(value.end_node) if hasattr(value.end_node, "items") else str(value.end_node.element_id)
                    edges_list.append(GraphEdge(
                        id=edge_id,
                        source=src_id,
                        target=tgt_id,
                        type=value.type,
                        properties=dict(value.items())
                    ))

                elif hasattr(value, "nodes") and hasattr(value, "relationships"):  # Path
                    for node in value.nodes:
                        _register_node(node)
                    for edge in value.relationships:
                        edge_id = str(edge.element_id)
                        src_id = _node_id(edge.start_node) if hasattr(edge.start_node, "items") else str(edge.start_node.element_id)
                        tgt_id = _node_id(edge.end_node) if hasattr(edge.end_node, "items") else str(edge.end_node.element_id)
                        edges_list.append(GraphEdge(
                            id=edge_id,
                            source=src_id,
                            target=tgt_id,
                            type=edge.type,
                            properties=dict(edge.items())
                        ))

        # Deduplicate edges by element_id
        unique_edges = {e.id: e for e in edges_list}
        return GraphResponse(
            nodes=list(nodes_dict.values()),
            edges=list(unique_edges.values())
        )

    async def get_network(self, year: Optional[int] = None) -> GraphResponse:
        """
        Returns the global bilateral trade network.
        Supports optional year filter for timeline replay (TN-06).
        Falls back to cached_network.json when Neo4j is offline (TN-02).
        """
        if year is not None:
            query = """
            MATCH (n:Country)-[r:EXPORTS_TO]->(m:Country)
            WHERE r.year = $year
            RETURN n, r, m
            ORDER BY n.iso3
            LIMIT 2000
            """
            params = {"year": year}
        else:
            query = """
            MATCH (n)-[r]->(m)
            RETURN n, r, m
            ORDER BY n.iso3
            LIMIT 2000
            """
            params = {}

        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            result = await self.run_query(query, params)
            if result.nodes:
                return result
            # Neo4j returned empty — fall back to cache
            log.info("Neo4j returned empty network, using offline cache")
            return _filter_cache_by_year(_load_fallback_cache(), year)
        except Exception as e:
            log.warning("Neo4j unavailable (%s) — serving offline cache", type(e).__name__)
            return _filter_cache_by_year(_load_fallback_cache(), year)

    async def get_neighbors(self, node_id: str, depth: int = 1) -> GraphResponse:
        """
        Returns neighboring nodes up to a specified depth.
        node_id must be a sovereign ISO3 code (e.g. "USA").
        Falls back to filtering the offline cache on Neo4j failure.
        """
        query = f"""
        MATCH p=(n)-[*1..{depth}]-(m)
        WHERE n.iso3 = $node_id
        RETURN p
        LIMIT 300
        """
        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            return await self.run_query(query, {"node_id": node_id})
        except Exception as e:
            log.warning("Neo4j neighbors query failed (%s) — filtering offline cache", type(e).__name__)
            cache = _load_fallback_cache()
            # Filter to nodes connected to the requested node
            connected_ids = {node_id}
            for edge in cache.edges:
                if edge.source == node_id:
                    connected_ids.add(edge.target)
                elif edge.target == node_id:
                    connected_ids.add(edge.source)
            filtered_nodes = [n for n in cache.nodes if n.id in connected_ids]
            filtered_edges = [
                e for e in cache.edges
                if e.source in connected_ids and e.target in connected_ids
            ]
            return GraphResponse(nodes=filtered_nodes, edges=filtered_edges)

    async def get_shortest_path(self, source_id: str, target_id: str) -> GraphResponse:
        """
        Returns the shortest trade path between two ISO3 nodes.
        Falls back to direct edge check in offline cache.
        """
        query = """
        MATCH p=shortestPath((n:Country)-[*]-(m:Country))
        WHERE n.iso3 = $source_id AND m.iso3 = $target_id
        RETURN p
        """
        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            return await self.run_query(query, {"source_id": source_id, "target_id": target_id})
        except Exception as e:
            log.warning("Neo4j path query failed (%s) — checking offline cache", type(e).__name__)
            cache = _load_fallback_cache()
            relevant_edges = [
                e for e in cache.edges
                if (e.source == source_id and e.target == target_id)
                or (e.source == target_id and e.target == source_id)
            ]
            relevant_node_ids = {source_id, target_id}
            relevant_nodes = [n for n in cache.nodes if n.id in relevant_node_ids]
            return GraphResponse(nodes=relevant_nodes, edges=relevant_edges)

    async def get_centrality(self):
        """
        Returns out-degree centrality as proxy for trade influence.
        Falls back to computing centrality from the offline cache.
        """
        query = """
        MATCH (n:Country)
        OPTIONAL MATCH (n)-[r:EXPORTS_TO]->()
        RETURN n.iso3 AS node_id, count(r) AS score
        ORDER BY score DESC
        LIMIT 15
        """
        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")

            async def fetch(tx):
                result = await tx.run(query)
                return await result.data()

            async with neo4j_conn.driver.session() as session:
                return await session.execute_read(fetch)
        except Exception as e:
            log.warning("Neo4j centrality query failed (%s) — computing from cache", type(e).__name__)
            # Compute out-degree centrality from offline cache
            cache = _load_fallback_cache()
            out_degree: Dict[str, int] = {}
            for edge in cache.edges:
                if edge.type == "EXPORTS_TO":
                    out_degree[edge.source] = out_degree.get(edge.source, 0) + 1
            sorted_centrality = sorted(out_degree.items(), key=lambda x: x[1], reverse=True)
            return [
                {"node_id": iso3, "score": float(score)}
                for iso3, score in sorted_centrality[:15]
            ]
