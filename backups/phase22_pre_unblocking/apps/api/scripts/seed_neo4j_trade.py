def load_trade_flows_csv(csv_path: Path, year_filter: int = None) -> dict:
    """
    Load trade flows from CSV. Returns dict keyed by (source, target, year).
    If year_filter is set, only loads rows for that year.
    """
    flows = defaultdict(lambda: {"export_value_usd": 0.0, "import_value_usd": 0.0})

    if not csv_path.exists():
        raise FileNotFoundError(
            f"Trade flows CSV not found: {csv_path}\n"
            f"Run the ETL pipeline first: python apps/api/ml/scripts/download/ingest_real_trade.py"
        )

    with open(csv_path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            year = int(row["year"])
            if year_filter and year != year_filter:
                continue
            key = (row["source_iso3"], row["target_iso3"], year)
            flows[key]["export_value_usd"] += float(row.get("export_value_usd") or 0)
            flows[key]["import_value_usd"] += float(row.get("import_value_usd") or 0)
    return dict(flows)


async def clear_database(tx):
    await tx.run("MATCH (n) DETACH DELETE n")


async def create_country_nodes(tx, iso3_set: set):
    for iso3 in sorted(iso3_set):
        meta = COUNTRY_META.get(iso3, {
            "name": iso3,
            "region": "Unknown",
            "income_group": "Unknown"
        })
        # Derive health/stability/risk from income group (deterministic, not random)
        health = {"High income": 0.88, "Upper middle income": 0.78,
                  "Lower middle income": 0.65, "Low income": 0.52}.get(meta["income_group"], 0.70)
        stability = {"High income": 0.86, "Upper middle income": 0.74,
                     "Lower middle income": 0.60, "Low income": 0.45}.get(meta["income_group"], 0.65)
        risk = {"High income": 0.18, "Upper middle income": 0.28,
                "Lower middle income": 0.42, "Low income": 0.58}.get(meta["income_group"], 0.35)

        await tx.run(
            """
            MERGE (c:Country {iso3: $iso3})
            SET c.name = $name,
                c.region = $region,
                c.income_group = $income_group,
                c.health = $health,
                c.stability = $stability,
                c.risk = $risk,
                c.shockValue = 0.0
            """,
            iso3=iso3,
            name=meta["name"],
            region=meta["region"],
            income_group=meta["income_group"],
            health=health,
            stability=stability,
            risk=risk,
        )


async def create_bloc_nodes(tx):
    for b in BLOCS:
        await tx.run(
            "MERGE (b:EconomicBloc {id: $id}) SET b.name = $name, b.type = $type",
            id=b["id"], name=b["name"], type=b["type"]
        )


async def create_memberships(tx, iso3_set: set):
    for bloc_id, members in MEMBERSHIPS.items():
        for iso3 in members:
            if iso3 not in iso3_set:
                continue
            await tx.run(
                """
                MATCH (c:Country {iso3: $iso3}), (b:EconomicBloc {id: $bloc_id})
                MERGE (c)-[:MEMBER_OF {joined_year: 2000}]->(b)
                """,
                iso3=iso3, bloc_id=bloc_id
            )


async def create_trade_relationships(tx, flows: dict):
    """Create EXPORTS_TO relationships from verified trade flow data. Zero random numbers."""
    for (source, target, year), vals in flows.items():
        exp_usd = vals["export_value_usd"]
        imp_usd = vals["import_value_usd"]
        if exp_usd <= 0 and imp_usd <= 0:
            continue  # Skip zero-value flows

        # Convert to billions for display
        exp_b = exp_usd / 1e9
        imp_b = imp_usd / 1e9
        net_balance_b = exp_b - imp_b
        # Dependency score normalized by world's largest bilateral corridor (~$600B)
        dependency = min(0.99, exp_b / 600.0)
        # Growth placeholder (real YoY data requires multi-year aggregation)
        growth = 0.0

        await tx.run(
            """
            MATCH (s:Country {iso3: $source}), (t:Country {iso3: $target})
            MERGE (s)-[r:EXPORTS_TO {year: $year, commodity_category: 'Total'}]->(t)
            SET r.tradeVolume = $trade_volume,
                r.importVolume = $import_volume,
                r.netBalance = $net_balance,
                r.dependencyScore = $dependency,
                r.growth = $growth,
                r.export_value_usd = $exp_usd,
                r.import_value_usd = $imp_usd
            """,
            source=source, target=target, year=year,
            trade_volume=round(exp_b, 3),
            import_volume=round(imp_b, 3),
            net_balance=round(net_balance_b, 3),
            dependency=round(dependency, 3),
            growth=growth,
            exp_usd=exp_usd,
            imp_usd=imp_usd,
        )


async def main():
    parser = argparse.ArgumentParser(description="Phase 22: Seed Neo4j from real bilateral trade data")
    parser.add_argument("--year", type=int, default=None,
                        help="Seed only a specific year (default: all years in CSV)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Load CSV and validate without writing to Neo4j")
    args = parser.parse_args()

    await logger.ainfo("Loading verified trade flow data from CSV...")
    flows = load_trade_flows_csv(TRADE_FLOWS_CSV, year_filter=args.year)
    await logger.ainfo(f"Loaded {len(flows):,} bilateral trade flow records (ZERO random numbers)")

    # Collect all ISO3 codes from the flow data
    iso3_set = set()
    for (src, tgt, yr) in flows:
        iso3_set.add(src)
        iso3_set.add(tgt)
    await logger.ainfo(f"Country coverage: {len(iso3_set)} economies")

    if args.dry_run:
        await logger.ainfo("DRY RUN — no changes written to Neo4j")
        return

    await logger.ainfo("Connecting to Neo4j...")
    await neo4j_conn.connect()

    async with neo4j_conn.driver.session() as session:
        await logger.ainfo("Clearing existing graph...")
        await session.execute_write(clear_database)

        await logger.ainfo("Creating country nodes...")
        await session.execute_write(create_country_nodes, iso3_set)

        await logger.ainfo("Creating economic bloc nodes...")
        await session.execute_write(create_bloc_nodes)

        await logger.ainfo("Creating economic bloc memberships...")
        await session.execute_write(create_memberships, iso3_set)

        await logger.ainfo("Creating real trade relationships (EXPORTS_TO)...")
        await session.execute_write(create_trade_relationships, flows)

    await neo4j_conn.close()
    await logger.ainfo(
        "Neo4j trade graph seeded successfully",
        countries=len(iso3_set),
        trade_flows=len(flows),
        blocs=len(BLOCS),
        data_source="World Bank / UN Comtrade (CC BY 4.0)",
        random_numbers_used=0,
    )


if __name__ == "__main__":
    asyncio.run(main())
