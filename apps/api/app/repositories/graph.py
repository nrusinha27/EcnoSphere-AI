"""
Phase 22 — Resilient GraphRepository with ISO3 Standardization
================================================================
Key features:
  TN-02 Fixed: Neo4j ServiceUnavailable is caught; falls back to
               cached_network.json offline snapshot.
               If BOTH Neo4j and fallback are unavailable, raises HTTP 503.
  TN-03 Fixed: Node IDs use iso3 property (e.g. "USA") throughout.
  TN-06 Support: get_network(year) accepts an optional year filter,
                 returning explicit NO_DATA (empty nodes/edges) for unobserved years.
  TN-09 Mitigation: Consistent deterministic order via iso3.
  METRICS Support: Comprehensive bilateral trade metrics calculation with
                   explicit sample coverage disclaimers and HHI concentration.
"""
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional, List
from fastapi import HTTPException

from app.neo4j.session import neo4j_conn
from app.schemas.graph import (
    GraphResponse, GraphNode, GraphEdge,
    TradeMetricsResponse, PartnerTradeMetric, CorridorMetricsResponse
)

log = logging.getLogger(__name__)

# Offline fallback cache generated by the Phase 22 ETL pipeline
_CACHE_PATH = Path(__file__).resolve().parents[4] / "data" / "processed" / "cached_network.json"

# In-memory cache of fallback data (loaded once on first failure)
_fallback_cache: Optional[GraphResponse] = None


def _cache_path_exists() -> bool:
    return _CACHE_PATH.exists()


def _load_fallback_cache() -> GraphResponse:
    """
    Load the offline cached network snapshot.
    Returns GraphResponse from cached_network.json.
    Caches result in memory after first load.
    Raises HTTPException 503 if fallback file is missing or corrupt.
    """
    global _fallback_cache
    if _fallback_cache is not None:
        return _fallback_cache

    if not _cache_path_exists():
        log.error("Offline cache file not found at %s — cannot serve fallback", _CACHE_PATH)
        raise HTTPException(
            status_code=503,
            detail="Trade network service unavailable: Neo4j database is offline and verified fallback cache is missing"
        )

    try:
        with open(_CACHE_PATH, encoding="utf-8") as f:
            data = json.load(f)

        nodes = [
            GraphNode(
                id=n["id"],
                label=n.get("label", "Country"),
                properties=n.get("properties", {})
            )
            for n in data.get("nodes", [])
        ]
        edges = [
            GraphEdge(
                id=e["id"],
                source=e["source"],
                target=e["target"],
                type=e.get("type", "EXPORTS_TO"),
                properties=e.get("properties", {})
            )
            for e in data.get("edges", [])
        ]
        if not nodes and not edges:
            raise HTTPException(
                status_code=503,
                detail="Trade network service unavailable: Fallback cache is empty"
            )

        _fallback_cache = GraphResponse(nodes=nodes, edges=edges)
        log.info(
            "Loaded offline trade network cache: %d nodes, %d edges",
            len(nodes), len(edges)
        )
        return _fallback_cache

    except (json.JSONDecodeError, KeyError, TypeError) as e:
        log.error("Failed to load offline cache: %s", e)
        raise HTTPException(
            status_code=503,
            detail=f"Trade network service unavailable: Fallback cache is corrupt ({e})"
        )


def _filter_cache_by_year(response: GraphResponse, year: Optional[int]) -> GraphResponse:
    """
    Filter the cached network edges by a specific year.
    If year is None, returns all edges.
    If year has no observations, returns an explicit empty graph (NO_DATA).
    """
    if year is None:
        return response
    filtered_edges = [
        e for e in response.edges
        if e.properties.get("year") == year
    ]
    if not filtered_edges:
        log.info("NO_DATA: No trade observations for requested year %d", year)
        return GraphResponse(nodes=[], edges=[])
    active_node_ids = {e.source for e in filtered_edges} | {e.target for e in filtered_edges}
    filtered_nodes = [n for n in response.nodes if n.id in active_node_ids]
    return GraphResponse(nodes=filtered_nodes, edges=filtered_edges)


class GraphRepository:
    """
    Repository for Neo4j trade knowledge graph with offline fallback.
    Node IDs are standardized to sovereign ISO3 codes throughout.
    """

    async def run_query(
        self,
        query: str,
        parameters: Dict[str, Any] = None
    ) -> GraphResponse:
        """
        Execute a Cypher read query against Neo4j.
        On ServiceUnavailable or driver failure, bubbles up exception to trigger fallback.
        """
        parameters = parameters or {}
        nodes_dict: Dict[str, GraphNode] = {}
        edges_list: list[GraphEdge] = []

        def _node_id(value) -> str:
            props = dict(value.items())
            iso3 = props.get("iso3") or props.get("id")
            if iso3:
                return str(iso3)
            return str(value.element_id)

        def _register_node(value) -> str:
            node_id = _node_id(value)
            if node_id not in nodes_dict:
                nodes_dict[node_id] = GraphNode(
                    id=node_id,
                    label=list(value.labels)[0] if value.labels else "Country",
                    properties=dict(value.items())
                )
            return node_id

        async def fetch_data(tx):
            result = await tx.run(query, parameters)
            return [record async for record in result]

        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            async with neo4j_conn.driver.session() as session:
                records = await session.execute_read(fetch_data)
        except Exception as e:
            log.warning("Neo4j query failed (%s): %s", type(e).__name__, e)
            raise

        for record in records:
            for key, value in record.items():
                if hasattr(value, "labels"):  # Node
                    _register_node(value)

                elif hasattr(value, "type") and hasattr(value, "start_node"):  # Relationship
                    edge_id = str(value.element_id)
                    src_id = _node_id(value.start_node) if hasattr(value.start_node, "items") else str(value.start_node.element_id)
                    tgt_id = _node_id(value.end_node) if hasattr(value.end_node, "items") else str(value.end_node.element_id)
                    edges_list.append(GraphEdge(
                        id=edge_id,
                        source=src_id,
                        target=tgt_id,
                        type=value.type,
                        properties=dict(value.items())
                    ))

                elif hasattr(value, "nodes") and hasattr(value, "relationships"):  # Path
                    for node in value.nodes:
                        _register_node(node)
                    for edge in value.relationships:
                        edge_id = str(edge.element_id)
                        src_id = _node_id(edge.start_node) if hasattr(edge.start_node, "items") else str(edge.start_node.element_id)
                        tgt_id = _node_id(edge.end_node) if hasattr(edge.end_node, "items") else str(edge.end_node.element_id)
                        edges_list.append(GraphEdge(
                            id=edge_id,
                            source=src_id,
                            target=tgt_id,
                            type=edge.type,
                            properties=dict(edge.items())
                        ))

        unique_edges = {e.id: e for e in edges_list}
        return GraphResponse(
            nodes=list(nodes_dict.values()),
            edges=list(unique_edges.values())
        )

    async def get_network(self, year: Optional[int] = None) -> GraphResponse:
        """
        Returns the global bilateral trade network.
        Supports optional year filter for timeline replay.
        Falls back to cached_network.json when Neo4j is offline.
        """
        if year is not None:
            query = """
            MATCH (n:Country)-[r:EXPORTS_TO]->(m:Country)
            WHERE r.year = $year
            RETURN n, r, m
            ORDER BY n.iso3
            LIMIT 2000
            """
            params = {"year": year}
        else:
            query = """
            MATCH (n:Country)-[r:EXPORTS_TO]->(m:Country)
            RETURN n, r, m
            ORDER BY n.iso3
            LIMIT 2000
            """
            params = {}

        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            result = await self.run_query(query, params)
            if result.nodes or result.edges:
                return result
            # Neo4j returned empty — check if this is an unobserved year
            if year is not None and year != 2022:
                log.info("NO_DATA for year %d in Neo4j", year)
                return GraphResponse(nodes=[], edges=[])
            # Otherwise fall back to cache
            log.info("Neo4j returned empty network, checking offline cache")
            return _filter_cache_by_year(_load_fallback_cache(), year)
        except Exception as e:
            log.warning("Neo4j unavailable (%s) — serving offline cache", type(e).__name__)
            return _filter_cache_by_year(_load_fallback_cache(), year)

    async def get_neighbors(self, node_id: str, depth: int = 1) -> GraphResponse:
        """
        Returns neighboring nodes up to a specified depth.
        node_id must be a sovereign ISO3 code (e.g. "USA").
        Falls back to filtering the offline cache on Neo4j failure.
        """
        query = f"""
        MATCH p=(n:Country)-[*1..{depth}]-(m:Country)
        WHERE n.iso3 = $node_id
        RETURN p
        LIMIT 300
        """
        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            return await self.run_query(query, {"node_id": node_id})
        except Exception as e:
            log.warning("Neo4j neighbors query failed (%s) — filtering offline cache", type(e).__name__)
            cache = _load_fallback_cache()
            connected_ids = {node_id}
            for edge in cache.edges:
                if edge.source == node_id:
                    connected_ids.add(edge.target)
                elif edge.target == node_id:
                    connected_ids.add(edge.source)
            filtered_nodes = [n for n in cache.nodes if n.id in connected_ids]
            filtered_edges = [
                e for e in cache.edges
                if e.source in connected_ids and e.target in connected_ids
            ]
            return GraphResponse(nodes=filtered_nodes, edges=filtered_edges)

    async def get_shortest_path(self, source_id: str, target_id: str) -> GraphResponse:
        """
        Returns the shortest trade path between two ISO3 nodes.
        Falls back to direct edge check in offline cache.
        """
        query = """
        MATCH p=shortestPath((n:Country)-[*]-(m:Country))
        WHERE n.iso3 = $source_id AND m.iso3 = $target_id
        RETURN p
        """
        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")
            return await self.run_query(query, {"source_id": source_id, "target_id": target_id})
        except Exception as e:
            log.warning("Neo4j path query failed (%s) — checking offline cache", type(e).__name__)
            cache = _load_fallback_cache()
            relevant_edges = [
                e for e in cache.edges
                if (e.source == source_id and e.target == target_id)
                or (e.source == target_id and e.target == source_id)
            ]
            relevant_node_ids = {source_id, target_id}
            relevant_nodes = [n for n in cache.nodes if n.id in relevant_node_ids]
            return GraphResponse(nodes=relevant_nodes, edges=relevant_edges)

    async def get_centrality(self) -> List[Dict[str, Any]]:
        """
        Returns out-degree centrality as proxy for trade influence.
        Falls back to computing centrality from the offline cache.
        """
        query = """
        MATCH (n:Country)
        OPTIONAL MATCH (n)-[r:EXPORTS_TO]->()
        RETURN n.iso3 AS node_id, count(r) AS score
        ORDER BY score DESC
        LIMIT 15
        """
        try:
            if neo4j_conn.driver is None:
                raise RuntimeError("Neo4j driver not initialized")

            async def fetch(tx):
                result = await tx.run(query)
                return await result.data()

            async with neo4j_conn.driver.session() as session:
                return await session.execute_read(fetch)
        except Exception as e:
            log.warning("Neo4j centrality query failed (%s) — computing from cache", type(e).__name__)
            cache = _load_fallback_cache()
            out_degree: Dict[str, int] = {}
            for edge in cache.edges:
                if edge.type == "EXPORTS_TO":
                    out_degree[edge.source] = out_degree.get(edge.source, 0) + 1
            sorted_centrality = sorted(out_degree.items(), key=lambda x: x[1], reverse=True)
            return [
                {"node_id": iso3, "score": float(score)}
                for iso3, score in sorted_centrality[:15]
            ]

    async def get_country_metrics(self, country_iso3: str, year: int = 2022) -> TradeMetricsResponse:
        """
        Computes reported bilateral trade metrics for an ISO3 country.
        Distinguishes partial corridor coverage from complete national accounts.
        """
        country_iso3 = country_iso3.strip().upper()
        # Retrieve network data (live or fallback)
        network = await self.get_network(year=year)
        if not network.nodes and not network.edges:
            raise HTTPException(
                status_code=404,
                detail=f"NO_DATA: No trade observations available for year {year}"
            )

        # Check if country exists in network
        has_country = any(n.id == country_iso3 for n in network.nodes)
        if not has_country:
            raise HTTPException(
                status_code=404,
                detail=f"NO_DATA: Economy '{country_iso3}' has no reported observations in the {year} preview dataset"
            )

        export_partners: List[PartnerTradeMetric] = []
        import_partners: List[PartnerTradeMetric] = []
        total_exp = 0.0
        total_imp = 0.0

        for edge in network.edges:
            edge_yr = edge.properties.get("year")
            if edge_yr != year:
                continue

            if edge.source == country_iso3:
                # Outgoing export
                exp_val = float(edge.properties.get("export_value_usd") or (float(edge.properties.get("tradeVolume", 0)) * 1e9))
                if exp_val > 0:
                    total_exp += exp_val
                    export_partners.append(PartnerTradeMetric(
                        partner_iso3=edge.target,
                        trade_value_usd=exp_val,
                        flow_direction="EXPORT"
                    ))
            elif edge.target == country_iso3:
                # Incoming import
                imp_val = float(edge.properties.get("import_value_usd") or 0.0)
                if imp_val > 0:
                    total_imp += imp_val
                    import_partners.append(PartnerTradeMetric(
                        partner_iso3=edge.source,
                        trade_value_usd=imp_val,
                        flow_direction="IMPORT"
                    ))

        # Sort partners by volume descending
        export_partners.sort(key=lambda x: x.trade_value_usd, reverse=True)
        import_partners.sort(key=lambda x: x.trade_value_usd, reverse=True)

        # Calculate Herfindahl-Hirschman Index (HHI) for export market concentration
        # HHI = sum((market_share_pct)^2)
        hhi = 0.0
        if total_exp > 0:
            for p in export_partners:
                share_pct = (p.trade_value_usd / total_exp) * 100.0
                hhi += share_pct ** 2

        net_balance = total_exp - total_imp

        return TradeMetricsResponse(
            country_iso3=country_iso3,
            year=year,
            total_reported_exports_usd=round(total_exp, 2),
            total_reported_imports_usd=round(total_imp, 2),
            reported_trade_balance_usd=round(net_balance, 2),
            trade_concentration_hhi=round(hhi, 2),
            is_complete_national_statistic=False,
            coverage_scope="UN_COMTRADE_2022_PREVIEW_SAMPLE (15 reporting economies)",
            coverage_disclaimer=(
                "Partial bilateral trade sample. Totals represent sum of observed "
                "bilateral corridors in UN Comtrade 2022 preview. Cannot be treated "
                "as exhaustive national account trade statistics."
            ),
            top_export_partners=export_partners[:10],
            top_import_partners=import_partners[:10]
        )

    async def get_corridor_metrics(self, source_iso3: str, target_iso3: str, year: int = 2022) -> CorridorMetricsResponse:
        """
        Returns bilateral corridor metrics between two ISO3 countries.
        """
        source_iso3 = source_iso3.strip().upper()
        target_iso3 = target_iso3.strip().upper()
        network = await self.get_network(year=year)

        matched_edge = next(
            (e for e in network.edges if e.source == source_iso3 and e.target == target_iso3 and e.properties.get("year") == year),
            None
        )

        if not matched_edge:
            raise HTTPException(
                status_code=404,
                detail=f"NO_DATA: No direct bilateral trade corridor observed for {source_iso3}->{target_iso3} in {year}"
            )

        exp_fob = matched_edge.properties.get("export_value_usd")
        imp_cif = matched_edge.properties.get("import_value_usd")
        trade_vol_b = matched_edge.properties.get("tradeVolume")
        persp = matched_edge.properties.get("perspective", "UNSPECIFIED")
        source_ds = matched_edge.properties.get("source", "UN_COMTRADE_2022_PREVIEW")

        return CorridorMetricsResponse(
            source_iso3=source_iso3,
            target_iso3=target_iso3,
            year=year,
            reported_export_fob_usd=float(exp_fob) if exp_fob is not None else None,
            reported_import_cif_usd=float(imp_cif) if imp_cif is not None else None,
            trade_volume_billions=float(trade_vol_b) if trade_vol_b is not None else None,
            perspective=persp,
            source_dataset=source_ds,
            coverage_disclaimer="Values reflect customs declarations reported under UN Comtrade 2022 preview."
        )
